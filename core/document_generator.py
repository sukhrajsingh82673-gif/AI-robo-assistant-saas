    def generate_document(
        self,
        title: str,
        format_type: Union[DocumentFormat, str],
        category: Union[DocumentCategory, str] = DocumentCategory.PERSONAL_DOCUMENT,
        content: str = "",
        metadata: Optional[Dict[str, Any]] = None,
        storage_boundary: Union[StorageBoundary, str] = StorageBoundary.PERSONAL,
        user_id: str = "usr_owner",
        tenant_id: str = "tnt_primary",
        company_id: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Generates an authentic document deliverable on disk, computes its SHA-256 hash,
        registers it in the database with searchable metadata, and returns artifact details.
        """
        fmt = str(format_type).upper()
        if fmt.startswith("DOCUMENTFORMAT."):
            fmt = fmt.split(".")[-1]

        boundary = str(storage_boundary).upper()
        if boundary.startswith("STORAGEBOUNDARY."):
            boundary = boundary.split(".")[-1]

        cat = str(category)
        if cat.startswith("DocumentCategory."):
            cat = cat.split(".")[-1]

        doc_id = f"doc_{uuid.uuid4().hex[:10]}"
        now = time.time()
        meta = metadata or {}
        meta["doc_id"] = doc_id
        meta["created_by"] = user_id
        meta["storage_boundary"] = boundary

        # 1. Generate Raw File Bytes
        if fmt == "PDF":
            file_bytes = self._build_native_pdf(title, content, meta)
            ext = "pdf"
        elif fmt == "DOCX":
            file_bytes = self._build_native_docx(title, content, meta)
            ext = "docx"
        elif fmt == "XLSX":
            file_bytes = self._build_native_xlsx(title, content, meta)
            ext = "xlsx"
        elif fmt == "PPTX":
            file_bytes = self._build_native_pptx(title, content, meta)
            ext = "pptx"
        elif fmt == "CSV":
            file_bytes = self._build_native_csv(title, content)
            ext = "csv"
        elif fmt == "JSON":
            try:
                parsed = json.loads(content)
                file_bytes = json.dumps(parsed, indent=2).encode("utf-8")
            except Exception:
                file_bytes = json.dumps({"title": title, "content": content, "timestamp": now}, indent=2).encode("utf-8")
            ext = "json"
        else:
            # Plain Text / Markdown
            file_bytes = f"# {title}\n\nGenerated: {time.ctime(now)}\n\n{content}".encode("utf-8")
            ext = "txt" if fmt == "TXT" else "md"

        # 2. Compute Cryptographic Digest
        sha256_hash = hashlib.sha256(file_bytes).hexdigest()
        size_bytes = len(file_bytes)

        # 3. Determine Safe Isolated Path & Write
        safe_name = "".join([c if c.isalnum() or c in ("-", "_") else "_" for c in title.lower()])[:40]
        filename = f"{safe_name}_{doc_id[:6]}.{ext}"
        target_dir = self._get_target_directory(boundary, user_id, company_id)
        file_path = os.path.join(target_dir, filename)

        with open(file_path, "wb") as f:
            f.write(file_bytes)

        # 4. Record in assistant_generated_documents
        with db.get_connection() as conn:
            conn.execute(
                """
                INSERT INTO assistant_generated_documents (
                    doc_id, tenant_id, company_id, user_id, storage_boundary,
                    title, format, category, file_path, size_bytes, sha256,
                    metadata, created_at
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    doc_id, tenant_id, company_id, user_id, boundary,
                    title, fmt, cat, file_path, size_bytes, sha256_hash,
                    json.dumps(meta), now
                )
            )

            # If corporate boundary, also cross-index into enterprise_files for departmental visibility
            if boundary == "COMPANY":
                try:
                    dept = meta.get("department", "Corporate")
                    conn.execute(
                        """
                        INSERT INTO enterprise_files (
                            file_id, tenant_id, company_id, department, name,
                            category, document_type, size_bytes, sha256, classification,
                            version, storage_path, linked_records, tags, uploaded_by,
                            summary, created_at, updated_at
                        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                        """,
                        (
                            doc_id, tenant_id, company_id or "comp_primary", dept, title,
                            "REPORT" if "REPORT" in cat.upper() else "EVIDENCE",
                            fmt, size_bytes, sha256_hash, "INTERNAL", 1, file_path,
                            json.dumps([]), json.dumps([cat, boundary]), user_id,
                            meta.get("summary", title), now, now
                        )
                    )
                except Exception:
                    pass

            conn.commit()

        download_url = f"/api/assistant/documents/{doc_id}/download"

        return {
            "doc_id": doc_id,
            "title": title,
            "format": fmt,
            "category": cat,
            "storage_boundary": boundary,
            "file_path": file_path,
            "filename": filename,
            "size_bytes": size_bytes,
            "sha256": sha256_hash,
            "download_url": download_url,
            "created_at": now
        }

