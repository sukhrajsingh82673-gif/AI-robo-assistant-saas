class DocumentGenerator:
    """
    Universal document production engine that produces valid, downloadable,
    native binary artifacts for PDF, DOCX, XLSX, PPTX, CSV, and text.
    """

    def __init__(self, base_storage_dir: Optional[str] = None):
        if base_storage_dir:
            self.base_dir = os.path.abspath(base_storage_dir)
        else:
            repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
            self.base_dir = os.path.join(repo_root, "storage")

    def _get_target_directory(
        self,
        storage_boundary: str,
        user_id: str,
        company_id: Optional[str] = None
    ) -> str:
        """Determines the isolated storage folder based on boundary."""
        safe_user = re.sub(r'[^A-Za-z0-9_.-]', '_', str(user_id or "usr_owner"))
        safe_comp = re.sub(r'[^A-Za-z0-9_.-]', '_', str(company_id or "comp_primary"))

        if storage_boundary == StorageBoundary.PERSONAL.value or storage_boundary == "PERSONAL":
            dir_path = os.path.join(self.base_dir, "personal", safe_user)
        else:
            dir_path = os.path.join(self.base_dir, "companies", safe_comp, "documents")
        os.makedirs(dir_path, exist_ok=True, mode=0o750)
        return dir_path

