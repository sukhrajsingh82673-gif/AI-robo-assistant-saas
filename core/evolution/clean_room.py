"""
ZONATA Clean-Room Tool Replication Engine (Sub-Step 6H).

Provides a legally compliant, air-gapped clean-room methodology to replicate required
tool capabilities when commercial tools cannot be purchased or hosted.
Features:
- Decision Ladder (first match wins): Open-Source -> Vendor API -> Clean-Room -> Infeasible.
- Strict Air-Gap separation: Specifier session vs. Implementer session with zero raw source sharing.
- Provenance Ledger (Rule 53): every requirement traced to PUBLIC_DOC, OPEN_SOURCE, OWNER_AUTHORED,
  or BLACK_BOX_OBSERVATION.
- Prohibited Input Filter (Rule 55): rejects decompiled/disassembled code, cracked binaries,
  leaked sources, and ToS scraping.
- Code Similarity Auditor: verifies zero copied identifiers, strings, or code structures.
- Legal Gate: inspects terms-of-service clauses and requires explicit human owner sign-off.
- Replicated tools tagged REPLICA with measured test coverage against owner requirements.
"""

import re
import uuid
import json
import hashlib
from datetime import datetime, timezone
from enum import Enum
from typing import Dict, List, Optional, Any, Set, Tuple

from core.evolution.principal import (
    PrincipalLike,
    is_human_principal,
    is_owner_principal,
)


class ProvenanceTrustClass(str, Enum):
    PUBLIC_DOC = "PUBLIC_DOC"
    OPEN_SOURCE = "OPEN_SOURCE"
    OWNER_AUTHORED = "OWNER_AUTHORED"
    BLACK_BOX_OBSERVATION = "BLACK_BOX_OBSERVATION"
    PROHIBITED = "PROHIBITED"


class DecisionLadderStep(str, Enum):
    OPEN_SOURCE_ALTERNATIVE = "OPEN_SOURCE_ALTERNATIVE"
    OFFICIAL_VENDOR_API = "OFFICIAL_VENDOR_API"
    CLEAN_ROOM_REPLICATION = "CLEAN_ROOM_REPLICATION"
    COMMERCIALLY_INFEASIBLE = "COMMERCIALLY_INFEASIBLE"


class CleanRoomError(Exception):
    """Base exception for clean-room protocol violations."""
    pass


class ProhibitedInputError(CleanRoomError):
    """Raised when prohibited inputs (decompiled code, cracks, leaked source) are detected (Rule 55)."""
    pass


class AirGapBoundaryViolationError(CleanRoomError):
    """Raised when an Implementer session attempts to access raw sources or forbidden storage."""
    pass


class LegalGateBlockedError(CleanRoomError):
    """Raised when ToS restricts reverse engineering or human owner approval is missing."""
    pass


class CodePlagiarismDetectedError(CleanRoomError):
    """Raised when candidate implementation exhibits high code/identifier similarity to reference sources."""
    pass


class ProhibitedInputDetector:
    """Detects prohibited content types in input documents."""

    DECOMPILED_INDICATORS = [
        re.compile(r"/\* Decompiled by (?:Ghidra|IDA Pro|JADX|dnSpy|ILSpy) \*/", re.IGNORECASE),
        re.compile(r"//\s*(?:Decompiled with|Generated by) CFR", re.IGNORECASE),
        re.compile(r"\b__asm\b|\b_fastcall\b|\b__stdcall\b"),
        re.compile(r"sub_[0-9a-fA-F]{4,8}\b"),  # Common IDA auto-named functions
        re.compile(r"dword_[0-9a-fA-F]{4,8}\b"),
    ]

    CRACK_INDICATORS = [
        re.compile(r"\bkeygen\b|\bcrack(?:ed)?\b|\bpatcher\b|\bbypass_license\b", re.IGNORECASE),
        re.compile(r"\bserial_generator\b|\bactivator\b", re.IGNORECASE),
    ]

    TOS_VIOLATION_TERMS = [
        re.compile(r"prohibit(?:s)?\s+(?:any\s+)?reverse\s+engineering", re.IGNORECASE),
        re.compile(r"shall\s+not\s+(?:decompile|disassemble|reverse\s+engineer)", re.IGNORECASE),
        re.compile(r"automated\s+scraping\s+or\s+extraction\s+is\s+strictly\s+forbidden", re.IGNORECASE),
    ]

    @classmethod
    def scan_content(cls, content: str) -> Tuple[bool, Optional[str]]:
        for pat in cls.DECOMPILED_INDICATORS:
            if pat.search(content):
                return False, "DECOMPILED_OR_DISASSEMBLED_CODE_DETECTED"
        for pat in cls.CRACK_INDICATORS:
            if pat.search(content):
                return False, "CRACK_OR_LICENSE_BYPASS_INDICATOR_DETECTED"
        return True, None

    @classmethod
    def scan_terms_of_service(cls, terms: str) -> List[str]:
        findings = []
        for pat in cls.TOS_VIOLATION_TERMS:
            if pat.search(terms):
                findings.append(pat.pattern)
        return findings


class ProvenanceRecord:
    """Immutable audit record for clean-room input material."""

    def __init__(
        self,
        record_id: str,
        source_name: str,
        trust_class: ProvenanceTrustClass,
        content_hash: str,
        license_info: str,
        retrieved_at: str,
        content_preview: str,
    ):
        self.record_id = record_id
        self.source_name = source_name
        self.trust_class = trust_class
        self.content_hash = content_hash
        self.license_info = license_info
        self.retrieved_at = retrieved_at
        self.content_preview = content_preview


class ProvenanceLedger:
    """Governed ledger tracking all allowed inputs for tool specifications."""

    def __init__(self):
        self._records: Dict[str, ProvenanceRecord] = {}

    def register_input(
        self,
        source_name: str,
        content: str,
        trust_class: ProvenanceTrustClass,
        license_info: str = "PUBLIC",
    ) -> ProvenanceRecord:
        # Check for prohibited input patterns
        clean, reason = ProhibitedInputDetector.scan_content(content)
        if not clean:
            prohibited_id = f"prov_err_{uuid.uuid4().hex[:8]}"
            raise ProhibitedInputError(
                f"Input rejected under Rule 55: {reason}. Uploads containing decompiled binaries, "
                f"cracks, or illicit dumps are strictly prohibited."
            )

        content_hash = hashlib.sha256(content.encode("utf-8")).hexdigest()
        rec_id = f"prov_{uuid.uuid4().hex[:10]}"
        record = ProvenanceRecord(
            record_id=rec_id,
            source_name=source_name,
            trust_class=trust_class,
            content_hash=content_hash,
            license_info=license_info,
            retrieved_at=datetime.now(timezone.utc).isoformat(),
            content_preview=content[:100],
        )
        self._records[rec_id] = record
        return record

    def get_record(self, record_id: str) -> Optional[ProvenanceRecord]:
        return self._records.get(record_id)


class CleanRoomSpec:
    """Air-gapped functional specification containing requirements without vendor code."""

    def __init__(
        self,
        tool_name: str,
        version: str,
        requirements: List[Dict[str, Any]],  # [{id, description, provenance_id, schema}]
        acceptance_tests: List[Dict[str, Any]],
        author_principal: str = "agent:specifier",
    ):
        self.tool_name = tool_name
        self.version = version
        self.requirements = requirements
        self.acceptance_tests = acceptance_tests
        self.author_principal = author_principal
        self.spec_hash = self._compute_hash()

    def _compute_hash(self) -> str:
        canonical = json.dumps(
            {
                "tool_name": self.tool_name,
                "version": self.version,
                "requirements": self.requirements,
                "acceptance_tests": self.acceptance_tests,
            },
            sort_keys=True,
            separators=(",", ":"),
            default=str,
        )
        return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


class AirGappedSpecifier:
    """Specifier session: consumes allowed documentation and produces clean functional spec."""

    @classmethod
    def author_specification(
        cls,
        tool_name: str,
        requirements_input: List[Dict[str, Any]],
        ledger: ProvenanceLedger,
    ) -> CleanRoomSpec:
        validated_requirements = []
        for req in requirements_input:
            prov_id = req.get("provenance_id")
            rec = ledger.get_record(prov_id)
            if not rec:
                raise CleanRoomError(f"Requirement '{req.get('id')}' lacks valid provenance citation.")
            if rec.trust_class == ProvenanceTrustClass.PROHIBITED:
                raise CleanRoomError(f"Requirement '{req.get('id')}' references PROHIBITED input.")

            validated_requirements.append(req)

        return CleanRoomSpec(
            tool_name=tool_name,
            version="1.0.0",
            requirements=validated_requirements,
            acceptance_tests=[
                {"test_id": f"test_{r.get('id')}", "description": f"Verify {r.get('id')} behavior"}
                for r in validated_requirements
            ],
            author_principal="agent:clean_room_specifier",
        )


class AirGappedImplementer:
    """Implementer session: air-gapped environment with access ONLY to CleanRoomSpec."""

    def __init__(self, spec: CleanRoomSpec):
        self.spec = spec
        self._forbidden_sources: Set[str] = set()

    def register_forbidden_context(self, source_ident: str) -> None:
        self._forbidden_sources.add(source_ident)

    def attempt_source_read(self, source_ident: str) -> str:
        """Spy test assertion: implementer cannot read original documents or vendor assets."""
        ident = str(source_ident)
        lowered = ident.lower()
        forbidden_markers = (
            "vendor", "doc", "proprietary", "binary", "decompil", "disassembl",
            "source_code", "source code", "http://", "https://", "../", "~",
        )
        if (
            source_ident in self._forbidden_sources
            or any(marker in lowered for marker in forbidden_markers)
            or "\\" in ident
            or ident.startswith("/")
            or re.search(r"\.(?:pdf|docx?|bin|exe|dll|zip|tar|gz|py|js|ts|c|cpp|java|go|rs)$", lowered)
        ):
            raise AirGapBoundaryViolationError(
                f"Air-gap boundary breach prevented: Implementer session is blocked from reading '{source_ident}'."
            )
        if lowered not in {"functional_spec", "specification", "open_standard"}:
            raise AirGapBoundaryViolationError(
                "Implementer session may only read the functional specification and open standards."
            )
        return "allowed"

    def implement_tool(self, implementation_code: Dict[str, str]) -> Dict[str, Any]:
        """Produces tool replica candidate."""
        return {
            "tool_name": self.spec.tool_name,
            "replica_tag": "REPLICA",
            "spec_hash": self.spec.spec_hash,
            "source_files": implementation_code,
            "status": "IMPLEMENTED",
        }


class CodeSimilarityAuditor:
    """Audits clean-room implementation for copied identifiers, strings, or structure."""

    @classmethod
    def audit_similarity(
        cls,
        candidate_code: str,
        vendor_reference_code: str,
        threshold: float = 0.35,
    ) -> Dict[str, Any]:
        # Extract token words of length >= 4
        def tokenize(code: str) -> Set[str]:
            identifiers = re.findall(r"\b[A-Za-z_][A-Za-z0-9_]{1,}\b", code)
            literals = re.findall(r"\"(?:[^\"\\]|\\.)*\"|'(?:[^'\\]|\\.)*'", code)
            return {token.lower() for token in identifiers + literals}

        cand_tokens = tokenize(candidate_code)
        ref_tokens = tokenize(vendor_reference_code)

        if not ref_tokens or not cand_tokens:
            return {"plagiarism_detected": False, "jaccard_similarity": 0.0, "colliding_tokens": []}

        intersection = cand_tokens.intersection(ref_tokens)
        union = cand_tokens.union(ref_tokens)
        similarity = len(intersection) / len(union)

        plagiarism_detected = similarity > threshold
        if plagiarism_detected:
            raise CodePlagiarismDetectedError(
                f"Code similarity threshold breached: {similarity:.2f} > {threshold:.2f}. "
                f"Colliding identifiers: {list(intersection)[:5]}"
            )

        return {
            "plagiarism_detected": False,
            "jaccard_similarity": similarity,
            "colliding_tokens": list(intersection),
        }


class CleanRoomLegalGate:
    """Evaluates vendor Terms of Service and enforces human owner approval."""

    @classmethod
    def evaluate_terms(cls, vendor_terms: str) -> Dict[str, Any]:
        violations = ProhibitedInputDetector.scan_terms_of_service(vendor_terms)
        prohibited = len(violations) > 0
        return {
            "prohibits_reverse_engineering": prohibited,
            "clauses_flagged": violations,
            "legal_recommendation": (
                "BLOCKED_BY_TERMS: Vendor contract expressly forbids reverse engineering. "
                "Clean-room replication cannot proceed without owner and legal review."
                if prohibited else "TERMS_PERMISSIVE: No express anti-reverse engineering clause found."
            ),
        }

    @classmethod
    def check_owner_authorization(
        cls, actor_principal: PrincipalLike, terms_evaluation: Dict[str, Any]
    ) -> bool:
        if terms_evaluation["prohibits_reverse_engineering"]:
            # If terms forbid it, must stop unless the authenticated owner
            # explicitly executes the legal override.
            if not is_owner_principal(actor_principal):
                raise LegalGateBlockedError(
                    "Legal Gate Blocked: Vendor terms prohibit reverse engineering and no authenticated owner override was provided."
                )
        if not is_human_principal(actor_principal):
            raise LegalGateBlockedError(
                "Human approval is mandatory to promote clean-room replicated tools."
            )
        return True


class DecisionLadder:
    """Evaluates alternative tool acquisition paths in priority order."""

    @classmethod
    def select_ladder_step(
        cls,
        has_open_source_alternative: bool,
        has_affordable_vendor_api: bool,
        clean_room_feasible: bool,
    ) -> DecisionLadderStep:
        # First match wins:
        # (1) Open-source alternative
        if has_open_source_alternative:
            return DecisionLadderStep.OPEN_SOURCE_ALTERNATIVE
        # (2) Official vendor API
        if has_affordable_vendor_api:
            return DecisionLadderStep.OFFICIAL_VENDOR_API
        # (3) Clean-room build
        if clean_room_feasible:
            return DecisionLadderStep.CLEAN_ROOM_REPLICATION
        # (4) Infeasible
        return DecisionLadderStep.COMMERCIALLY_INFEASIBLE
